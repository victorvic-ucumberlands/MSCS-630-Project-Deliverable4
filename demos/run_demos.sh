#!/usr/bin/env bash
# run_demos.sh - run every demo script through ./myshell and keep the evidence.
#
# Each demo runs in a fresh scratch directory (so file operations are safe and
# repeatable), with stdin from /dev/null, and its full transcript - commands
# echoed by `myshell -e`, program output and diagnostics - is written to
# evidence/<name>.log.  Afterwards a set of automatic checks (PASS/FAIL) is
# evaluated against the logs and written to evidence/SUMMARY.txt.
#
#   ./demos/run_demos.sh                    run everything (evidence/ is recreated)
#   ./demos/run_demos.sh 08_roundrobin ...  re-run only the named demos, keep the
#                                           other logs, and re-evaluate every check
set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SH_REAL="$ROOT/myshell"
OUT="$ROOT/evidence"
DEMOS="$ROOT/demos"

[ -x "$SH_REAL" ] || { echo "build first: make" >&2; exit 1; }
# Deliverable 4: every shell has to log in.  The demos and tests run as admin
# through a small wrapper (-u admin, with the demo password), against their
# own throw-away user database and file tree; nothing touches ./.myshell or ./fs.
TESTDB="$(mktemp -d)"
export MYSHELL_HOME="$TESTDB/.myshell" MYSHELL_FS="$TESTDB/fs"
"$SH_REAL" --setup-demo >/dev/null || { echo "demo setup failed" >&2; exit 1; }
mkdir -p "$ROOT/build"
SH="$ROOT/build/myshell-admin"
printf '#!/bin/sh\nMYSHELL_PASSWORD=admin123 exec "%s" -u admin "$@"\n' "$SH_REAL" > "$SH"
chmod +x "$SH"
password_of() { case "$1" in admin) echo admin123;; alice) echo alice123;; bob) echo bob12345;; guest) echo guest123;; esac; }
[ -x "$ROOT/demos/cpuburn" ] || { echo "build first: make (demos/cpuburn is missing)" >&2; exit 1; }
ONLY=("$@")
if [ ${#ONLY[@]} -eq 0 ]; then rm -rf "$OUT"; fi
mkdir -p "$OUT"
want() {                                       # want <demo name>: is it selected?
  [ ${#ONLY[@]} -eq 0 ] && return 0
  local x; for x in "${ONLY[@]}"; do [ "$x" = "$1" ] && return 0; done
  return 1
}

